// UI localization. Source strings are Russian and double as lookup keys;
// `ru` returns them unchanged, `en` maps them through `en` / `backend` below.
// Reactivity: the BarWidget root calls attach(); reading holder.uiLang inside
// tr() makes every QML binding that calls it re-evaluate on a language change.

var SUPPORTED = ["en", "ru"]
var holder = null

function attach(object) { holder = object; return true }

// "auto" (or anything unknown) follows the system locale; unsupported system
// languages fall back to English.
function detect() {
  var names = []
  try {
    var locale = Qt.locale()
    names = (locale.uiLanguages || []).concat([locale.name])
  } catch (error) {}
  for (var i = 0; i < names.length; ++i) {
    var code = String(names[i] || "").toLowerCase().split(/[-_.@]/)[0]
    if (SUPPORTED.indexOf(code) >= 0) return code
  }
  return "en"
}

function resolve(preference) {
  return SUPPORTED.indexOf(preference) >= 0 ? preference : detect()
}

function lang() {
  var value = holder ? holder.uiLang : ""
  return SUPPORTED.indexOf(value) >= 0 ? value : detect()
}

function decimal() { return lang() === "ru" ? "," : "." }

function fill(text, args) {
  for (var i = 0; i < args.length; ++i) text = text.split("%" + (i + 1)).join(String(args[i]))
  return text
}

function tr(text) {
  if (lang() === "ru") return text
  var out = Object.prototype.hasOwnProperty.call(en, text) ? en[text] : text
  return arguments.length > 1 ? fill(out, Array.prototype.slice.call(arguments, 1)) : out
}

// Russian one/few/many; English "singular|plural" taken from the first form's translation.
function plural(count, one, few, many) {
  if (lang() === "ru") {
    var n = Math.abs(count) % 100, m = n % 10
    if (n > 10 && n < 20) return many
    if (m > 1 && m < 5) return few
    return m === 1 ? one : many
  }
  var forms = String(one).split("|")
  return Math.abs(count) === 1 || forms.length < 2 ? forms[0] : forms[1]
}

// Text produced by the backend (errors, default names). Exact match first, then patterns.
function tb(text) {
  text = String(text === undefined || text === null ? "" : text)
  if (lang() === "ru" || text === "") return text
  if (Object.prototype.hasOwnProperty.call(backend, text)) return backend[text]
  if (Object.prototype.hasOwnProperty.call(en, text)) return en[text]
  for (var i = 0; i < patterns.length; ++i) {
    var match = patterns[i][0].exec(text)
    if (match) return text.replace(patterns[i][0], patterns[i][1])
  }
  return text
}

